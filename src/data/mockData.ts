export function generateMetricHistory(points: number = 30): MetricDataPoint[] {
  const history: MetricDataPoint[] = [];
  const now = Date.now();
  const stepMs = 5000;

  for (let i = points - 1; i >= 0; i--) {
    const time = new Date(now - i * stepMs);
    const s1 = Math.floor(40 + Math.random() * 15);
    const s2 = Math.floor(38 + Math.random() * 14);
    const s3 = Math.floor(39 + Math.random() * 16);
    const totalRps = s1 + s2 + s3;
    const failed = Math.random() < 0.2 ? Math.floor(Math.random() * 3) : 0;
    const avgLat = Number((16 + Math.random() * 6).toFixed(1));

    history.push({
      timestamp: time.toISOString(),
      formattedTime: time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' }),
      requestsPerSecond: totalRps,
      successfulRequests: totalRps - failed,
      failedRequests: failed,
      errorRate: Number(((failed / totalRps) * 100).toFixed(2)),
      avgLatencyMs: avgLat,
      p50LatencyMs: Number((avgLat * 0.9).toFixed(1)),
      p95LatencyMs: Number((avgLat * 1.8).toFixed(1)),
      p99LatencyMs: Number((avgLat * 2.5).toFixed(1)),
      server1Requests: s1,
      server2Requests: s2,
      server3Requests: s3,
      algorithm: 'dynamic-load-balancing',
    });
  }

  return history;
}
